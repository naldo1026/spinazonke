// Scans public/photos/<player>/ and writes src/data/photos.ts.
// Runs automatically before `npm run dev`, `npm run build` and `npm test`.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const players = ['ronaldo', 'kyle', 'keanan'];
const imageExt = /\.(jpe?g|png|webp|gif|avif)$/i;

const manifest = {};
for (const id of players) {
  const dir = join(root, 'public', 'photos', id);
  const files = existsSync(dir) ? readdirSync(dir).filter((f) => imageExt.test(f) && !f.startsWith('.')) : [];
  files.sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
  manifest[id] = files.map((f) => `photos/${id}/${f}`);
}

const body = players.map((id) => `  ${id}: ${JSON.stringify(manifest[id])},`).join('\n');
const out = `// Generated by scripts/gen-photos.mjs from public/photos/. Don't edit by hand.
import type { PlayerId } from '../types';

export const PHOTO_MANIFEST: Record<PlayerId, string[]> = {
${body}
};
`;

const target = join(root, 'src', 'data', 'photos.ts');
// Only write on change so the dev server doesn't reload for nothing.
if (!existsSync(target) || readFileSync(target, 'utf8') !== out) {
  writeFileSync(target, out);
}
const counts = players.map((id) => `${id}: ${manifest[id].length}`).join(', ');
console.log(`[photos] ${counts}`);
